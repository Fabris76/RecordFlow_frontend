import { useCallback, useEffect, useState } from 'react';
import PageHeader from '../../components/PageHeader';
import LoadingSpinner from '../../components/LoadingSpinner';
import ErrorMessage from '../../components/ErrorMessage';
import Button from '../../components/Button';
import { createBackup, downloadBackup, getBackups, restoreBackup } from '../../services/backupService';
import './Backups.css';

const size = (bytes) => { const value = Number(bytes || 0); return value < 1024 ? `${value} B` : value < 1024 * 1024 ? `${(value / 1024).toFixed(1)} KB` : `${(value / (1024 * 1024)).toFixed(1)} MB`; };

export default function Backups() {
  const [backups, setBackups] = useState([]);
  const [pagination, setPagination] = useState({ total: 0, totalPages: 1 });
  const [page, setPage] = useState(1);
  const [loading, setLoading] = useState(true);
  const [working, setWorking] = useState('');
  const [error, setError] = useState('');
  const [message, setMessage] = useState('');
  const load = useCallback(async () => {
    setLoading(true); setError('');
    try { const response = await getBackups({ page, limit: 20 }); setBackups(Array.isArray(response.data) ? response.data : []); setPagination(response.pagination || { total: 0, totalPages: 1 }); }
    catch (requestError) { setError(requestError.message || 'Unable to load backups. Please try again.'); }
    finally { setLoading(false); }
  }, [page]);
  useEffect(() => { load(); }, [load]);
  const handleCreate = async () => {
    setWorking('create'); setError(''); setMessage('');
    try { await createBackup(); setPage(1); setMessage('Database backup created successfully.'); await load(); }
    catch (requestError) { setError(requestError.message || 'Database backup failed.'); }
    finally { setWorking(''); }
  };
  const handleDownload = async (backup) => {
    setWorking(`download-${backup.id}`); setError('');
    try { await downloadBackup(backup.id, backup.filename); }
    catch (requestError) { setError(requestError.message || 'Backup download is unavailable.'); }
    finally { setWorking(''); }
  };
  const handleRestore = async (backup) => {
    if (!window.confirm(`Restore the database from ${backup.filename}? A safety backup will be created first.`)) return;
    setWorking(`restore-${backup.id}`); setError(''); setMessage('');
    try { await restoreBackup(backup.id); setMessage('Database restored successfully.'); await load(); }
    catch (requestError) { setError(requestError.message || 'Database restore failed.'); }
    finally { setWorking(''); }
  };
  return <div className="backups-page">
    <div className="backups-heading"><PageHeader eyebrow="Owner workspace" title="Backups" description="Create, download, and restore protected database backups." /><Button onClick={handleCreate} disabled={loading || Boolean(working)}>{working === 'create' ? 'Creating backup...' : 'Create backup'}</Button></div>
    <section className="backups-notice"><span aria-hidden="true">✓</span><div><strong>Protected database snapshots</strong><p>Backups are generated by the backend and recorded for accountability. Restores create a safety backup before changing the database.</p></div></section>
    {message && <div className="backups-success" role="status">{message}</div>}
    {error && <div className="backups-error"><ErrorMessage>{error}</ErrorMessage><Button variant="outline" onClick={load}>Try again</Button></div>}
    {loading ? <LoadingSpinner label="Loading backups" /> : <section className="backups-card">{backups.length ? <><div className="backups-table-wrap"><table className="backups-table"><thead><tr><th>Backup file</th><th>Created by</th><th>Created at</th><th>Size</th><th>Status</th><th>Actions</th></tr></thead><tbody>{backups.map((backup) => <tr key={backup.id}><td><strong>{backup.filename}</strong></td><td>{backup.created_by_name}</td><td>{new Date(backup.created_at).toLocaleString('en-GH')}</td><td>{size(backup.file_size)}</td><td><span className={`backup-status backup-status--${String(backup.status).toLowerCase()}`}>{backup.status}</span></td><td><div className="backup-actions"><button type="button" onClick={() => handleDownload(backup)} disabled={Boolean(working)}>{working === `download-${backup.id}` ? 'Preparing...' : 'Download'}</button><button type="button" className="backup-restore-button" onClick={() => handleRestore(backup)} disabled={Boolean(working) || backup.status !== 'COMPLETED'}>{working === `restore-${backup.id}` ? 'Restoring...' : 'Restore'}</button></div></td></tr>)}</tbody></table></div><div className="backups-pagination"><span>{pagination.total || 0} backups</span><div><button type="button" disabled={page <= 1 || Boolean(working)} onClick={() => setPage((current) => current - 1)}>Previous</button><strong>Page {page} of {pagination.totalPages || 1}</strong><button type="button" disabled={page >= (pagination.totalPages || 1) || Boolean(working)} onClick={() => setPage((current) => current + 1)}>Next</button></div></div></> : <div className="backups-empty"><strong>No backups created yet</strong><span>Create a protected snapshot to see it here.</span></div>}</section>}
  </div>;
}
